import { readFile, writeFile } from "node:fs/promises";
const runtime = await readFile(
  new URL("../templates/runtime.ts", import.meta.url),
  "utf8",
);
const license = await readFile(new URL("../LICENSE", import.meta.url), "utf8");
const hooks = await readFile(
  new URL("../templates/hooks.ts", import.meta.url),
  "utf8",
);
await writeFile(
  new URL("../src/core/templates.ts", import.meta.url),
  `// Generated by scripts/embed-templates.mjs. Edit templates/ instead.\nexport const RUNTIME_SOURCE=${JSON.stringify(runtime)};\nexport const HOOKS_SOURCE=${JSON.stringify(hooks)};\nexport const RUNTIME_LICENSE=${JSON.stringify(license)};\n`,
);
